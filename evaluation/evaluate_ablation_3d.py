def _load_eval_sequence(
    trajectory_path: Path | None,
    glb_path: Path | None,
    asset: AssetGeometry,
    args: argparse.Namespace,
) -> tuple[SequenceData, str | None]:
    source = str(args.sequence_source or "glb").strip().lower()
    warnings = []
    if source in {"glb", "mesh", "auto"} and glb_path is not None and glb_path.exists():
        try:
            return load_glb_sequence(glb_path, asset, int(args.num_points_per_link)), None
        except Exception as exc:
            if source in {"glb", "mesh"}:
                raise
            warnings.append(f"glb_load_failed:{exc}")
    if trajectory_path is None or not trajectory_path.exists():
        raise FileNotFoundError("Missing prediction/GT trajectory fallback")
    seq = load_trajectory(trajectory_path)
    return seq, ";".join(warnings) if warnings else None


def evaluate_variant(
    case_meta: dict[str, Any],
    row: dict[str, Any],
    annotation: dict[str, Any],
    asset: AssetGeometry,
    gt_seq: SequenceData,
    pred_seq: SequenceData,
    gt_plan: dict[str, Any] | None,
    variant: str,
    args: argparse.Namespace,
    gt_phase_static_rows: list[dict[str, Any]] | None = None,
) -> tuple[dict[str, Any], list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
    if gt_phase_static_rows:
        phases = [
            {"id": str(row.get("phase_id") or f"phase_{i}"), "order": i}
            for i, row in enumerate(gt_phase_static_rows)
        ]
        phase_ids = [str(p.get("id") or "") for p in phases]
        gt_indices = list(range(len(gt_phase_static_rows)))
        gt_frames = [gt_seq.frames[i] for i in gt_indices]
        dyn_links = []
        for row, phase_id in zip(gt_phase_static_rows, phase_ids):
            links = [ln for ln in _json_list(row.get("dynamic_links")) if ln in asset.visual_links]
            if not links:
                links = dynamic_links_for_phase(annotation, phase_id, asset)
            dyn_links.append(links)
    else:
        phases = sorted(phases_from_annotation(annotation), key=lambda p: _phase_order(p, 0))
        endpoint_by_phase = phase_endpoint_times(phases, gt_plan=gt_plan)
        phase_ids = [str(p.get("id") or "") for p in phases]
        gt_indices = [nearest_frame_index(gt_seq, endpoint_by_phase.get(str(p.get("id") or ""), 0.0)) for p in phases]
        gt_frames = [gt_seq.frames[i] for i in gt_indices]
        dyn_links = [dynamic_links_for_phase(annotation, str(p.get("id") or ""), asset) for p in phases]
    score_matrix = preliminary_similarity_matrix(asset, gt_frames, pred_seq, dyn_links, args)
    strict_match = not bool(args.allow_equal_frames)
    pred_indices = ordered_match(score_matrix, strict=strict_match)
    overlap_prev = overlap_allowed_from_previous(annotation, phase_ids)
    pred_indices = apply_overlap_matching_windows(score_matrix, pred_indices, overlap_prev, strict=strict_match)

    matched = {
        "case_id": case_meta.get("case_id"),
        "asset_name": case_meta.get("asset_name"),
        "action_name": case_meta.get("action_name"),
        "variant": variant,
        "gt_frame_indices": gt_indices,
        "gt_timestamps": [gt_seq.frames[i].time_s for i in gt_indices],
        "pred_frame_indices": pred_indices,
        "pred_timestamps": [pred_seq.frames[i].time_s for i in pred_indices],
        "phases": phase_ids,
        "overlap_allowed_from_previous": overlap_prev,
        "gt_sequence_source": gt_seq.source,
        "gt_static_glbs": [str(row.get("static_glb") or "") for row in gt_phase_static_rows] if gt_phase_static_rows else None,
        "gt_source_frame_indices": [
            int(row.get("trajectory_frame_index", i)) for i, row in enumerate(gt_phase_static_rows)
        ] if gt_phase_static_rows else None,
    }
    per_link_rows: list[dict[str, Any]] = []
    per_phase_rows: list[dict[str, Any]] = []
    def add_state_metrics(
        phase_index: int,
        phase_id: str,
        gt_frame_index: int,
        pred_frame_index: int,
        dynamic: list[str],
    ) -> None:
        gt_frame = gt_seq.frames[gt_frame_index]
        pred_frame = pred_seq.frames[pred_frame_index]
        static = [ln for ln in asset.visual_links if ln not in set(dynamic)]
        phase_link_rows = []
        relevant = list(dict.fromkeys(dynamic + static))
        for link in relevant:
            vals = link_metrics(asset, pred_frame, gt_frame, link, args)
            row_link = {
                **case_meta,
                "variant": variant,
                "phase_index": phase_index,
                "phase_id": phase_id,
                "link": link,
                "group": "dynamic" if link in dynamic else "static",
                **vals,
            }
            per_link_rows.append(row_link)
            phase_link_rows.append(row_link)
        dyn_m = aggregate_metrics(phase_link_rows, dynamic)
        stat_m = aggregate_metrics(phase_link_rows, static)
        overall = weighted_overall(dyn_m, stat_m, args)
        per_phase_rows.append(
            {
                **case_meta,
                "variant": variant,
                "phase_index": phase_index,
                "phase_id": phase_id,
                "gt_frame_index": gt_frame_index,
                "pred_frame_index": pred_frame_index,
                "gt_time_s": gt_frame.time_s,
                "pred_time_s": pred_frame.time_s,
                "dynamic_links": dynamic,
                "static_links_count": len(static),
                "PN_gIoU": overall["PN_gIoU"],
                "PN_PC": overall["PN_PC"],
                "PN_OC": overall["PN_OC"],
                "Dynamic_gIoU": dyn_m["PN_gIoU"],
                "Dynamic_PC": dyn_m["PN_PC"],
                "Dynamic_OC": dyn_m["PN_OC"],
                "Static_gIoU": stat_m["PN_gIoU"],
                "Static_PC": stat_m["PN_PC"],
                "Static_OC": stat_m["PN_OC"],
            }
        )

    for pi, phase in enumerate(phases):
        phase_id = str(phase.get("id") or f"phase_{pi}")
        add_state_metrics(pi, phase_id, gt_indices[pi], pred_indices[pi], dyn_links[pi])

    if not bool(args.disable_terminal_state_check) and gt_seq.frames and pred_seq.frames:
        # Ordered best-frame matching intentionally allows timing flexibility, but it can
        # otherwise ignore wrong extra motion after the last matched key state. Always
        # compare the final rendered prediction against the final GT state as an
        # additional all-part consistency state.
        add_state_metrics(
            len(phases),
            "__terminal_final_state__",
            len(gt_seq.frames) - 1,
            len(pred_seq.frames) - 1,
            list(asset.visual_links),
        )
        matched["terminal_gt_frame_index"] = len(gt_seq.frames) - 1
        matched["terminal_pred_frame_index"] = len(pred_seq.frames) - 1
        matched["terminal_gt_timestamp"] = gt_seq.frames[-1].time_s
        matched["terminal_pred_timestamp"] = pred_seq.frames[-1].time_s

    def mean_phase(key: str) -> float | None:
        policy = str(args.terminal_score_policy or "min").strip().lower()
        if policy == "average":
            vals = [float(r[key]) for r in per_phase_rows if r.get(key) is not None and math.isfinite(float(r[key]))]
            return float(np.mean(vals)) if vals else None
        nonterminal_vals = [
            float(r[key])
            for r in per_phase_rows
            if r.get("phase_id") != "__terminal_final_state__"
            and r.get(key) is not None
            and math.isfinite(float(r[key]))
        ]
        base = float(np.mean(nonterminal_vals)) if nonterminal_vals else None
        terminal_vals = [
            float(r[key])
            for r in per_phase_rows
            if r.get("phase_id") == "__terminal_final_state__"
            and r.get(key) is not None
            and math.isfinite(float(r[key]))
        ]
        terminal = terminal_vals[0] if terminal_vals else None
        if base is None:
            return terminal
        if terminal is None:
            return base
        return min(base, terminal)

    per_case = {
        **case_meta,
        "variant": variant,
        "PN_gIoU": mean_phase("PN_gIoU"),
        "PN_PC": mean_phase("PN_PC"),
        "PN_OC": mean_phase("PN_OC"),
        "Dynamic_gIoU": mean_phase("Dynamic_gIoU"),
        "Dynamic_PC": mean_phase("Dynamic_PC"),
        "Dynamic_OC": mean_phase("Dynamic_OC"),
        "Static_gIoU": mean_phase("Static_gIoU"),
        "Static_PC": mean_phase("Static_PC"),
        "Static_OC": mean_phase("Static_OC"),
        "matched_frame_indices": pred_indices,
        "matched_timestamps": matched["pred_timestamps"],
        "num_phases": len(phases),
        "num_eval_states": len(per_phase_rows),
    }
    return per_case, per_phase_rows, per_link_rows, [matched], matched


def _compiled_class_from_template_dir(name: str) -> str:
    if name.endswith("_constraint_templates"):
        return name[: -len("_constraint_templates")]
    if name.endswith("_variant_templates"):
        return name[: -len("_variant_templates")]
    if name.endswith("_templates"):
        return name[: -len("_templates")]
    return name


def _infer_asset_root(row: dict[str, Any], cls: str, asset: str) -> Path | None:
    path = _as_path(row.get("asset_root"))
    if path is not None and path.exists():
        return path
    case_id = str(row.get("case_id") or "")
    output_root = case_id.split(":", 1)[0] if ":" in case_id else ""
    candidates: list[Path] = []
    if output_root == "non_causal_output" or cls == "non_causal":
        candidates.append(REPO_ROOT / "data" / "not_causal_data" / asset)
    else:
        candidates.append(REPO_ROOT / "data" / "causal_data" / asset)
    candidates.extend(
        [
            REPO_ROOT / "data" / "causal_data" / asset,
            REPO_ROOT / "data" / "not_causal_data" / asset,
            REPO_ROOT / "hard_case" / asset,
        ]
    )
    for cand in candidates:
        if cand.exists():
            return cand.resolve()
    return None


def _infer_source_dir(row: dict[str, Any], asset: str, action: str) -> Path | None:
    source_plan = _as_path(row.get("plan_path"))
    if source_plan is not None and source_plan.exists():
        return source_plan.parent
    case_id = str(row.get("case_id") or "")
    output_root = case_id.split(":", 1)[0] if ":" in case_id else ""
    roots = []
    if output_root:
        roots.append(REPO_ROOT / output_root)
    roots.extend([REPO_ROOT / "casual_output", REPO_ROOT / "causal_output", REPO_ROOT / "non_causal_output"])
    for root in roots:
        for cand in (
            root / asset / action / asset,
            root / asset / action,
            root / asset,
        ):
            if (cand / "trajectory.jsonl").exists() or (cand / "plan.json").exists():
                return cand.resolve()
    return None


