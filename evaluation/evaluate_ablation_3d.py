def phases_from_annotation(annotation: dict[str, Any]) -> list[dict[str, Any]]:
    phases = annotation.get("phases")
    if isinstance(phases, list) and phases:
        return [p for p in phases if isinstance(p, dict)]
    seen = []
    for c in annotation.get("constraints") or []:
        if not isinstance(c, dict):
            continue
        phase = str(c.get("phase") or "").strip()
        if phase and phase not in seen:
            seen.append(phase)
    return [{"id": p, "order": i, "preferred_duration_s": None} for i, p in enumerate(seen)]


def phase_endpoint_times(phases: list[dict[str, Any]], gt_plan: dict[str, Any] | None = None) -> dict[str, float]:
    if not isinstance(gt_plan, dict):
        raise ValueError("Missing GT plan timeline for phase endpoint matching")
    by_name: dict[str, float] = {}
    for seg in gt_plan.get("timeline") or []:
        if not isinstance(seg, dict) or seg.get("name") is None:
            continue
        if seg.get("t1") is None:
            raise ValueError(f"GT plan timeline segment has no t1: {seg.get('name')}")
        by_name[str(seg.get("name"))] = float(seg.get("t1"))
    missing = [str(p.get("id") or "") for p in phases if str(p.get("id") or "") not in by_name]
    if missing:
        available = sorted(by_name)
        raise ValueError(f"GT plan timeline missing phase endpoint(s): {missing}; available={available}")
    return {str(p.get("id") or ""): by_name[str(p.get("id") or "")] for p in phases}


def nearest_frame_index(seq: SequenceData, t: float) -> int:
    times = np.asarray([f.time_s for f in seq.frames], dtype=float)
    return int(np.argmin(np.abs(times - float(t))))


def dynamic_links_for_phase(annotation: dict[str, Any], phase_id: str, asset: AssetGeometry) -> list[str]:
    out: list[str] = []
    for c in annotation.get("constraints") or []:
        if not isinstance(c, dict) or str(c.get("phase") or "") != phase_id:
            continue
        subject = str(c.get("subject") or "")
        if subject in asset.child_link_by_joint:
            link = asset.child_link_by_joint[subject]
        elif subject in asset.visual_links:
            link = subject
        else:
            continue
        if link in asset.visual_links and link not in out:
            out.append(link)
    return out


def _weighted_match_score(
    asset: AssetGeometry,
    pred_frame: TrajectoryFrame,
    gt_frame: TrajectoryFrame,
    dynamic_links: list[str],
    args: argparse.Namespace,
) -> float:
    dynamic = list(dict.fromkeys([ln for ln in dynamic_links if ln in asset.visual_links]))
    static = [ln for ln in asset.visual_links if ln not in set(dynamic)]

    def mean_giou(links: list[str]) -> float | None:
        vals = []
        for link in links:
            v = aabb_giou(transformed_vertices(asset, pred_frame, link), transformed_vertices(asset, gt_frame, link))
            if v is not None and math.isfinite(float(v)):
                vals.append(float(v))
        return float(np.mean(vals)) if vals else None

    d = mean_giou(dynamic or asset.visual_links)
    s = mean_giou(static)
    if d is None and s is None:
        return -1.0
    if d is None:
        return float(s)
    if s is None:
        return float(d)
    return float(args.dynamic_weight) * float(d) + float(args.static_weight) * float(s)


def preliminary_similarity_matrix(
    asset: AssetGeometry,
    gt_frames: list[TrajectoryFrame],
    pred_seq: SequenceData,
    phase_dynamic_links: list[list[str]],
    args: argparse.Namespace,
) -> np.ndarray:
    mat = np.zeros((len(gt_frames), len(pred_seq.frames)), dtype=np.float32)
    for k, gt_frame in enumerate(gt_frames):
        for t, pred_frame in enumerate(pred_seq.frames):
            mat[k, t] = _weighted_match_score(asset, pred_frame, gt_frame, phase_dynamic_links[k], args)
    return mat


def ordered_match(score: np.ndarray, strict: bool = True) -> list[int]:
    k_count, t_count = score.shape
    if k_count == 0 or t_count == 0:
        return []
    dp = np.full((k_count, t_count), -np.inf, dtype=np.float64)
    back = np.full((k_count, t_count), -1, dtype=np.int32)
    dp[0, :] = score[0, :]
    for k in range(1, k_count):
        best_val = -np.inf
        best_idx = -1
        for t in range(t_count):
            prev_t = t - 1 if strict else t
            if prev_t >= 0 and dp[k - 1, prev_t] > best_val:
                best_val = float(dp[k - 1, prev_t])
                best_idx = int(prev_t)
            if best_idx >= 0:
                dp[k, t] = best_val + float(score[k, t])
                back[k, t] = best_idx
    end = int(np.argmax(dp[-1, :]))
    if not np.isfinite(dp[-1, end]):
        # Fallback for very short predictions: nearest monotonic spacing.
        return [min(t_count - 1, i) for i in range(k_count)]
    out = [end]
    for k in range(k_count - 1, 0, -1):
        end = int(back[k, end])
        out.append(end)
    out.reverse()
    return out


def overlap_allowed_from_previous(annotation: dict[str, Any], phase_ids: list[str]) -> list[bool]:
    out = [False for _ in phase_ids]
    index = {phase_id: i for i, phase_id in enumerate(phase_ids)}
    for rel in annotation.get("relations") or []:
        if not isinstance(rel, dict) or not bool(rel.get("overlap_allowed")):
            continue
        from_phase = str(rel.get("from_phase") or "")
        to_phase = str(rel.get("to_phase") or "")
        j = index.get(to_phase)
        if j is None or j <= 0:
            continue
        if phase_ids[j - 1] == from_phase:
            out[j] = True
    return out


def apply_overlap_matching_windows(
    score: np.ndarray,
    pred_indices: list[int],
    overlap_prev: list[bool],
    strict: bool = True,
) -> list[int]:
    if score.size == 0 or not pred_indices:
        return pred_indices
    t_count = int(score.shape[1])
    out = [min(t_count - 1, max(0, int(x))) for x in pred_indices]
    for i in range(min(len(out), len(overlap_prev))):
        if not overlap_prev[i]:
            continue
        if i >= score.shape[0]:
            continue
        # For A -> B overlap, B may start from the phase before A. This is the
        # matching-time counterpart of "score B inside the preceding state to
        # next-state window" and does not estimate timing from annotation durations.
        if i >= 2:
            lo = out[i - 2] + (1 if strict else 0)
        else:
            lo = 0
        if i + 1 < len(out):
            hi = out[i + 1] - (1 if strict else 0)
        else:
            hi = t_count - 1
        lo = max(0, min(t_count - 1, int(lo)))
        hi = max(0, min(t_count - 1, int(hi)))
        if lo > hi:
            lo, hi = 0, t_count - 1
        window = np.asarray(score[i, lo : hi + 1], dtype=np.float32)
        if window.size:
            out[i] = int(lo + int(np.argmax(window)))
    return out


