def stable_seed(seed_text: str) -> int:
    digest = hashlib.sha256(str(seed_text).encode("utf-8")).digest()
    return int.from_bytes(digest[:4], byteorder="little", signed=False)


@dataclass
class TrajectoryFrame:
    frame_idx: int
    time_s: float
    joint_angles: dict[str, float]
    base_tf: np.ndarray
    mesh_vertices_by_link: dict[str, np.ndarray] | None = None
    mesh_points_by_link: dict[str, np.ndarray] | None = None


@dataclass
class SequenceData:
    path: Path
    frames: list[TrajectoryFrame]
    source: str = "trajectory"


@dataclass
class AssetGeometry:
    asset_root: Path
    links: dict[str, Any]
    joints: list[dict[str, Any]]
    child_link_by_joint: dict[str, str]
    visual_links: list[str]
    vertices_by_link: dict[str, np.ndarray]
