def _find_urdf(asset_root: Path) -> Path:
    mobility = asset_root / "mobility.urdf"
    if mobility.exists():
        return mobility
    try:
        return next(asset_root.rglob("*.urdf"))
    except StopIteration:
        raise FileNotFoundError(f"No URDF under {asset_root}")


def _merge_meshes(meshes: list[Any]) -> trimesh.Trimesh | None:
    usable = []
    for mesh in meshes or []:
        if mesh is None:
            continue
        if isinstance(mesh, trimesh.Scene):
            mesh = rp._scene_to_mesh_simple(mesh)
        if getattr(mesh, "vertices", None) is None or len(mesh.vertices) == 0:
            continue
        usable.append(mesh)
    if not usable:
        return None
    if len(usable) == 1:
        return usable[0].copy()
    return trimesh.util.concatenate([m.copy() for m in usable])


def _deterministic_sample(mesh: trimesh.Trimesh, n: int, seed_text: str) -> np.ndarray:
    if n <= 0 or mesh is None or len(mesh.vertices) == 0:
        return np.zeros((0, 3), dtype=np.float32)
    state = np.random.get_state()
    seed = stable_seed(seed_text)
    np.random.seed(seed)
    try:
        if getattr(mesh, "faces", None) is not None and len(mesh.faces) > 0:
            pts = mesh.sample(int(n))
        else:
            verts = np.asarray(mesh.vertices, dtype=np.float32)
            if len(verts) <= n:
                pts = verts
            else:
                idx = np.random.choice(len(verts), size=int(n), replace=False)
                pts = verts[idx]
    finally:
        np.random.set_state(state)
    return np.asarray(pts, dtype=np.float32)


def load_asset_geometry(asset_root: Path, num_points_per_link: int, scale_floor_ratio: float) -> AssetGeometry:
    urdf = _find_urdf(asset_root)
    links, joints = rp.parse_urdf(urdf)
    link_meshes = rp.load_link_meshes(links, urdf.parent, textured=False)
    child_link_by_joint = {str(j.get("name")): str(j.get("child")) for j in joints if j.get("name") and j.get("child")}
    vertices_by_link: dict[str, np.ndarray] = {}
    points_by_link: dict[str, np.ndarray] = {}
    scale_by_link: dict[str, float] = {}
    visual_links: list[str] = []
    all_bounds = []
    merged_by_link: dict[str, trimesh.Trimesh] = {}
    for link_name in sorted(links):
        merged = _merge_meshes(link_meshes.get(link_name) or [])
        if merged is None:
            continue
        merged_by_link[link_name] = merged
        verts = np.asarray(merged.vertices, dtype=np.float32)
        if verts.size == 0:
            continue
        visual_links.append(link_name)
        vertices_by_link[link_name] = verts
        points_by_link[link_name] = _deterministic_sample(merged, num_points_per_link, f"{asset_root}:{link_name}:{num_points_per_link}")
        b = np.asarray(merged.bounds, dtype=float)
        all_bounds.append(b)
        diag = float(np.linalg.norm(b[1] - b[0]))
        scale_by_link[link_name] = max(diag, 1.0e-9)
    if all_bounds:
        mins = np.min(np.stack([b[0] for b in all_bounds], axis=0), axis=0)
        maxs = np.max(np.stack([b[1] for b in all_bounds], axis=0), axis=0)
        obj_diag = float(np.linalg.norm(maxs - mins))
    else:
        obj_diag = 1.0
    floor = max(1.0e-9, float(scale_floor_ratio) * obj_diag)
    for link_name in list(scale_by_link):
        scale_by_link[link_name] = max(scale_by_link[link_name], floor)
    return AssetGeometry(
        asset_root=asset_root,
        links=links,
        joints=joints,
        child_link_by_joint=child_link_by_joint,
        visual_links=visual_links,
        vertices_by_link=vertices_by_link,
        points_by_link=points_by_link,
        scale_by_link=scale_by_link,
    )


def _transform_points(points: np.ndarray, tf: np.ndarray) -> np.ndarray:
    pts = np.asarray(points, dtype=np.float32)
    if pts.size == 0:
        return np.zeros((0, 3), dtype=np.float32)
    homog = np.concatenate([pts, np.ones((pts.shape[0], 1), dtype=np.float32)], axis=1)
    out = homog @ np.asarray(tf, dtype=np.float32).T
    return np.asarray(out[:, :3], dtype=np.float32)


def frame_link_transforms(asset: AssetGeometry, frame: TrajectoryFrame) -> dict[str, np.ndarray]:
    return rp.compute_link_transforms(asset.links, asset.joints, frame.joint_angles, base_tf=frame.base_tf)


def transformed_vertices(asset: AssetGeometry, frame: TrajectoryFrame, link: str) -> np.ndarray:
    if frame.mesh_vertices_by_link is not None:
        return frame.mesh_vertices_by_link.get(link, np.zeros((0, 3), dtype=np.float32))
    tf = frame_link_transforms(asset, frame).get(link, np.eye(4))
    return _transform_points(asset.vertices_by_link.get(link, np.zeros((0, 3), dtype=np.float32)), tf)


def transformed_points(asset: AssetGeometry, frame: TrajectoryFrame, link: str) -> np.ndarray:
    if frame.mesh_points_by_link is not None:
        return frame.mesh_points_by_link.get(link, np.zeros((0, 3), dtype=np.float32))
    tf = frame_link_transforms(asset, frame).get(link, np.eye(4))
    return _transform_points(asset.points_by_link.get(link, np.zeros((0, 3), dtype=np.float32)), tf)


def _frame_object_bounds(asset: AssetGeometry, frame: TrajectoryFrame, links: list[str] | None = None) -> tuple[np.ndarray, np.ndarray] | None:
    chunks = []
    for link in links or asset.visual_links:
        verts = transformed_vertices(asset, frame, link)
        if verts.size:
            chunks.append(np.asarray(verts, dtype=np.float32))
    if not chunks:
        return None
    pts = np.concatenate(chunks, axis=0)
    return np.min(pts, axis=0), np.max(pts, axis=0)


def _diag_from_bounds(bounds: tuple[np.ndarray, np.ndarray] | None) -> float | None:
    if bounds is None:
        return None
    return float(np.linalg.norm(np.asarray(bounds[1], dtype=float) - np.asarray(bounds[0], dtype=float)))


def _center_from_bounds(bounds: tuple[np.ndarray, np.ndarray]) -> np.ndarray:
    return 0.5 * (np.asarray(bounds[0], dtype=np.float32) + np.asarray(bounds[1], dtype=np.float32))


def _gt_frame_link_scales(asset: AssetGeometry, gt_seq: SequenceData, scale_floor_ratio: float) -> dict[str, float]:
    if not gt_seq.frames:
        return dict(asset.scale_by_link)
    frame = gt_seq.frames[0]
    out: dict[str, float] = {}
    all_bounds = []
    for link in asset.visual_links:
        verts = transformed_vertices(asset, frame, link)
        b = _bbox(verts)
        if b is None:
            continue
        all_bounds.append(b)
        out[link] = max(float(np.linalg.norm(np.asarray(b[1]) - np.asarray(b[0]))), 1.0e-9)
    if all_bounds:
        mins = np.min(np.stack([b[0] for b in all_bounds], axis=0), axis=0)
        maxs = np.max(np.stack([b[1] for b in all_bounds], axis=0), axis=0)
        floor = max(1.0e-9, float(scale_floor_ratio) * float(np.linalg.norm(maxs - mins)))
    else:
        floor = 1.0e-9
    for link in list(out):
        out[link] = max(out[link], floor)
    merged = dict(asset.scale_by_link)
    merged.update(out)
    return merged


def normalize_prediction_geometry_to_gt(
    asset: AssetGeometry,
    pred_seq: SequenceData,
    gt_seq: SequenceData,
    mode: str,
) -> tuple[SequenceData, dict[str, Any] | None]:
    """Normalize cross-asset geometry scale without changing the predicted center path.

    `shape_scale_to_gt` is intended for Particulate-vs-source comparisons where
    the exported URDF/GLB was normalized to a different object size.  It scales
    each predicted frame about that frame's object center, preserving transport
    direction and distance while comparing similarly sized rendered geometry.
    """
    mode = str(mode or "none").strip().lower()
    if mode in {"", "none"}:
        return pred_seq, None
    if mode != "shape_scale_to_gt":
        raise ValueError(f"Unknown geometry normalization mode: {mode}")
    if not pred_seq.frames or not gt_seq.frames:
        return pred_seq, {"mode": mode, "applied": False, "reason": "empty_sequence"}
    gt_bounds = _frame_object_bounds(asset, gt_seq.frames[0])
    pred_bounds = _frame_object_bounds(asset, pred_seq.frames[0])
    gt_diag = _diag_from_bounds(gt_bounds)
    pred_diag = _diag_from_bounds(pred_bounds)
    if gt_diag is None or pred_diag is None or gt_diag <= 1.0e-9 or pred_diag <= 1.0e-9:
        return pred_seq, {
            "mode": mode,
            "applied": False,
            "reason": "invalid_initial_bounds",
            "gt_initial_diag": gt_diag,
            "pred_initial_diag": pred_diag,
        }
    scale = float(gt_diag) / float(pred_diag)
    if not math.isfinite(scale) or scale <= 0.0:
        return pred_seq, {
            "mode": mode,
            "applied": False,
            "reason": "invalid_scale",
            "gt_initial_diag": gt_diag,
            "pred_initial_diag": pred_diag,
            "scale": scale,
        }
    if abs(scale - 1.0) <= 1.0e-6:
        return pred_seq, {
            "mode": mode,
            "applied": False,
            "reason": "scale_is_one",
            "gt_initial_diag": gt_diag,
            "pred_initial_diag": pred_diag,
            "scale": scale,
        }

    frames: list[TrajectoryFrame] = []
    for frame in pred_seq.frames:
        bounds = _frame_object_bounds(asset, frame)
        if bounds is None:
            frames.append(frame)
            continue
        center = _center_from_bounds(bounds)
        verts_by_link: dict[str, np.ndarray] = {}
        points_by_link: dict[str, np.ndarray] = {}
        for link in asset.visual_links:
            verts = transformed_vertices(asset, frame, link)
            pts = transformed_points(asset, frame, link)
            if verts.size:
                verts_by_link[link] = np.asarray(center + scale * (np.asarray(verts, dtype=np.float32) - center), dtype=np.float32)
            if pts.size:
                points_by_link[link] = np.asarray(center + scale * (np.asarray(pts, dtype=np.float32) - center), dtype=np.float32)
        frames.append(
            TrajectoryFrame(
                frame_idx=frame.frame_idx,
                time_s=frame.time_s,
                joint_angles=dict(frame.joint_angles),
                base_tf=np.asarray(frame.base_tf, dtype=float).copy(),
                mesh_vertices_by_link=verts_by_link,
                mesh_points_by_link=points_by_link,
            )
        )
    return SequenceData(path=pred_seq.path, frames=frames, source=f"{pred_seq.source}+shape_scale_to_gt"), {
        "mode": mode,
        "applied": True,
        "gt_initial_diag": gt_diag,
        "pred_initial_diag": pred_diag,
        "scale": scale,
        "center_path_preserved": True,
    }


def _bbox(points: np.ndarray) -> tuple[np.ndarray, np.ndarray] | None:
    pts = np.asarray(points, dtype=float)
    if pts.ndim != 2 or pts.shape[0] == 0:
        return None
    return np.min(pts, axis=0), np.max(pts, axis=0)


def _vol(mins: np.ndarray, maxs: np.ndarray) -> float:
    d = np.maximum(np.asarray(maxs) - np.asarray(mins), 0.0)
    return float(d[0] * d[1] * d[2])


def aabb_giou(pred: np.ndarray, gt: np.ndarray) -> float | None:
    bp = _bbox(pred)
    bg = _bbox(gt)
    if bp is None or bg is None:
        return None
    p0, p1 = bp
    g0, g1 = bg
    i0 = np.maximum(p0, g0)
    i1 = np.minimum(p1, g1)
    inter = _vol(i0, i1)
    vp = _vol(p0, p1)
    vg = _vol(g0, g1)
    union = vp + vg - inter
    iou = inter / union if union > 1.0e-12 else 1.0
    c0 = np.minimum(p0, g0)
    c1 = np.maximum(p1, g1)
    cv = _vol(c0, c1)
    if cv <= 1.0e-12:
        return float(iou)
    return float(iou - (cv - union) / cv)


def _mean_nearest_distance(a: np.ndarray, b: np.ndarray, chunk: int = 256) -> float:
    if a.size == 0 or b.size == 0:
        return float("inf")
    vals = []
    b = np.asarray(b, dtype=np.float32)
    for i in range(0, len(a), chunk):
        aa = np.asarray(a[i : i + chunk], dtype=np.float32)
        diff = aa[:, None, :] - b[None, :, :]
        d2 = np.sum(diff * diff, axis=2)
        vals.append(np.sqrt(np.min(d2, axis=1)))
    return float(np.mean(np.concatenate(vals, axis=0)))


def _mean_nearest_distance_torch(a: np.ndarray, b: np.ndarray, device: str, chunk: int = 1024) -> float:
    if a.size == 0 or b.size == 0:
        return float("inf")
    import torch

    dev = torch.device(device)
    aa_all = torch.as_tensor(np.asarray(a, dtype=np.float32), device=dev)
    bb = torch.as_tensor(np.asarray(b, dtype=np.float32), device=dev)
    vals = []
    with torch.no_grad():
        for i in range(0, int(aa_all.shape[0]), int(chunk)):
            aa = aa_all[i : i + int(chunk)]
            dist = torch.cdist(aa, bb, p=2)
            vals.append(torch.min(dist, dim=1).values.detach().cpu())
    return float(torch.cat(vals, dim=0).mean().item())


def _mean_nearest_distance_pytorch3d(a: np.ndarray, b: np.ndarray, device: str, chunk: int = 4096) -> float:
    if a.size == 0 or b.size == 0:
        return float("inf")
    import torch
    from pytorch3d.ops import knn_points

    dev = torch.device(device)
    aa_all = torch.as_tensor(np.asarray(a, dtype=np.float32), device=dev)
    bb = torch.as_tensor(np.asarray(b, dtype=np.float32), device=dev)[None, :, :]
    vals = []
    with torch.no_grad():
        for i in range(0, int(aa_all.shape[0]), int(chunk)):
            aa = aa_all[i : i + int(chunk)][None, :, :]
            # PyTorch3D returns squared L2 distances.
            d2 = knn_points(aa, bb, K=1, return_nn=False).dists[0, :, 0]
            vals.append(torch.sqrt(torch.clamp(d2, min=0.0)).detach().cpu())
    return float(torch.cat(vals, dim=0).mean().item())


def _pc_backend(args: argparse.Namespace) -> tuple[str, str | None]:
    backend = str(getattr(args, "pc_backend", "numpy") or "numpy").strip().lower()
    if backend == "auto":
        backend = "pytorch3d" if getattr(args, "cuda_device", None) is not None else "numpy"
    device_id = getattr(args, "cuda_device", None)
    if backend in {"torch", "pytorch3d"} and device_id is not None:
        return backend, f"cuda:{int(device_id)}"
    if backend in {"torch", "pytorch3d"}:
        return backend, "cuda:0"
    return "numpy", None


def point_consistency(pred: np.ndarray, gt: np.ndarray, scale: float, tau: float, args: argparse.Namespace) -> float | None:
    if pred.size == 0 or gt.size == 0:
        return None
    backend, device = _pc_backend(args)
    if backend == "torch":
        try:
            chunk = int(getattr(args, "torch_chunk", 1024) or 1024)
            cd = 0.5 * (
                _mean_nearest_distance_torch(pred, gt, str(device), chunk=chunk)
                + _mean_nearest_distance_torch(gt, pred, str(device), chunk=chunk)
            )
        except Exception:
            if not bool(getattr(args, "pc_fallback_numpy", True)):
                raise
            cd = 0.5 * (_mean_nearest_distance(pred, gt) + _mean_nearest_distance(gt, pred))
    elif backend == "pytorch3d":
        try:
            chunk = int(getattr(args, "pytorch3d_chunk", getattr(args, "torch_chunk", 4096)) or 4096)
            cd = 0.5 * (
                _mean_nearest_distance_pytorch3d(pred, gt, str(device), chunk=chunk)
                + _mean_nearest_distance_pytorch3d(gt, pred, str(device), chunk=chunk)
            )
        except Exception:
            if not bool(getattr(args, "pc_fallback_numpy", True)):
                raise
            cd = 0.5 * (_mean_nearest_distance(pred, gt) + _mean_nearest_distance(gt, pred))
    else:
        cd = 0.5 * (_mean_nearest_distance(pred, gt) + _mean_nearest_distance(gt, pred))
    cd_norm = float(cd) / max(float(scale), 1.0e-9)
    return float(math.exp(-cd_norm / max(float(tau), 1.0e-9)))


def occupancy_consistency(pred: np.ndarray, gt: np.ndarray, resolution: int) -> float | None:
    if pred.size == 0 or gt.size == 0:
        return None
    pts = np.concatenate([pred, gt], axis=0)
    mins = np.min(pts, axis=0)
    maxs = np.max(pts, axis=0)
    extent = np.maximum(maxs - mins, 1.0e-9)
    pad = 0.02 * float(np.max(extent))
    mins = mins - pad
    maxs = maxs + pad
    extent = np.maximum(maxs - mins, 1.0e-9)

    def vox(x: np.ndarray) -> set[tuple[int, int, int]]:
        idx = np.floor((x - mins) / extent * float(resolution)).astype(np.int32)
        idx = np.clip(idx, 0, int(resolution) - 1)
        return set(map(tuple, idx.tolist()))

    pv = vox(np.asarray(pred, dtype=np.float32))
    gv = vox(np.asarray(gt, dtype=np.float32))
    if not pv and not gv:
        return 1.0
    if not pv or not gv:
        return 0.0
    inter = len(pv & gv)
    precision = inter / max(1, len(pv))
    recall = inter / max(1, len(gv))
    if precision + recall <= 1.0e-12:
        return 0.0
    return float(2.0 * precision * recall / (precision + recall))


def link_metrics(asset: AssetGeometry, pred: TrajectoryFrame, gt: TrajectoryFrame, link: str, args: argparse.Namespace) -> dict[str, float | None]:
    pred_vertices = transformed_vertices(asset, pred, link)
    gt_vertices = transformed_vertices(asset, gt, link)
    pred_pts = transformed_points(asset, pred, link)
    gt_pts = transformed_points(asset, gt, link)
    return {
        "PN_gIoU": aabb_giou(pred_vertices, gt_vertices),
        "PN_PC": point_consistency(pred_pts, gt_pts, asset.scale_by_link.get(link, 1.0), float(args.tau), args),
        "PN_OC": occupancy_consistency(pred_pts, gt_pts, int(args.voxel_resolution)),
    }


def _mean_metric(rows: list[dict[str, Any]], metric: str) -> float | None:
    vals = [float(r[metric]) for r in rows if r.get(metric) is not None and math.isfinite(float(r[metric]))]
    return float(np.mean(vals)) if vals else None


def aggregate_metrics(rows: list[dict[str, Any]], links: list[str]) -> dict[str, float | None]:
    keep = [r for r in rows if str(r.get("link")) in set(links)]
    return {m: _mean_metric(keep, m) for m in METRICS}


def weighted_overall(dynamic: dict[str, float | None], static: dict[str, float | None], args: argparse.Namespace) -> dict[str, float | None]:
    out = {}
    for m in METRICS:
        d = dynamic.get(m)
        s = static.get(m)
        if d is None and s is None:
            out[m] = None
        elif d is None:
            out[m] = s
        elif s is None:
            out[m] = d
        else:
            out[m] = float(args.dynamic_weight) * d + float(args.static_weight) * s
    return out


