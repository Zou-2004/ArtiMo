def evaluate_case(case: dict[str, Any], args: argparse.Namespace) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]]]:
    ann_path = _as_path(case.get("annotation_path"))
    if ann_path is None or not ann_path.exists():
        raise FileNotFoundError(f"Missing annotation_path for case: {case}")
    row, annotation = parse_annotation_case(ann_path)
    asset_root = _as_path(case.get("asset_root") or row.get("asset_root"))
    if asset_root is None or not asset_root.exists():
        raise FileNotFoundError(f"Missing asset_root for case: {ann_path}")
    gt_path = _resolve_sequence_path(case.get("gt_trajectory") or case.get("gt_sequence") or case.get("gt_dir"))
    gt_glb_path = _resolve_existing_path(case.get("gt_glb") or case.get("gt_animated_glb"))
    if gt_path is None and gt_glb_path is None:
        raise FileNotFoundError(f"Missing gt trajectory/GLB for case: {ann_path}")
    gt_plan_path = _resolve_plan_path(case.get("gt_plan_json") or case.get("gt_plan") or case.get("gt_dir"))
    gt_plan = _read_json(gt_plan_path) if gt_plan_path is not None else None
