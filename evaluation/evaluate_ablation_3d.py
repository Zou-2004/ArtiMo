def main() -> int:
    args = parse_args()
    out_dir = Path(args.out_dir).resolve()
    diagnose_dir = out_dir / "diagnose"
    cases = load_cases(args)
    if not cases:
        print("[ERROR] No matching cases found. Check --asset/--action names against benchmark sidecar asset_name/action_name.", file=sys.stderr)
        return 2
    _write_json(diagnose_dir / "resolved_manifest.json", {"cases": cases})
    if args.write_resolved_manifest:
        _write_json(Path(args.write_resolved_manifest).resolve(), {"cases": cases})
    per_case_rows: list[dict[str, Any]] = []
    per_phase_rows: list[dict[str, Any]] = []
    per_link_rows: list[dict[str, Any]] = []
    matched_rows: list[dict[str, Any]] = []
    errors: list[dict[str, Any]] = []
    args_dict = vars(args).copy()
    concise_fields = ["case_id", "class", "asset_name", "action_name", "variant", "PN_gIoU", "PN_PC", "PN_OC"]
    partial_csv = out_dir / "ablation_metrics.partial.csv"
    partial_jsonl = diagnose_dir / "per_case_metrics.partial.jsonl"
    partial_errors_jsonl = diagnose_dir / "errors.partial.jsonl"
    for partial in (partial_csv, partial_jsonl, partial_errors_jsonl):
        if partial.exists():
            partial.unlink()

    def absorb(result: dict[str, Any]) -> None:
        pc_rows = result.get("per_case") or []
        pp_rows = result.get("per_phase") or []
        pl_rows = result.get("per_link") or []
        mf_rows = result.get("matched") or []
        er_rows = result.get("errors") or []
        per_case_rows.extend(pc_rows)
        per_phase_rows.extend(pp_rows)
        per_link_rows.extend(pl_rows)
        matched_rows.extend(mf_rows)
        errors.extend(er_rows)
        if pc_rows:
            _append_jsonl(partial_jsonl, pc_rows)
            _append_csv(partial_csv, concise_metric_rows(pc_rows), concise_fields)
        if er_rows:
            _append_jsonl(partial_errors_jsonl, er_rows)
        fatal = result.get("fatal_error")
        if fatal:
            errors.append(fatal)
            _append_jsonl(partial_errors_jsonl, [fatal])
            print(f"[ERROR] {result.get('idx')}/{len(cases)} {result.get('label')}: {fatal.get('error')}", flush=True)
            return
        print(
            f"[OK] {result.get('idx')}/{len(cases)} {result.get('label')} "
            f"variants={len(pc_rows)} errors={len(er_rows)} "
            f"partial_csv={partial_csv}"
            ,
            flush=True,
        )
        for row in pc_rows:
            if row.get("prediction_warning"):
                print(
                    f"[WARN] {result.get('label')} {row.get('variant')}: {row.get('prediction_warning')} "
                    f"({row.get('prediction_glb') or row.get('prediction_trajectory')})",
                    flush=True,
                )

    workers = max(1, int(args.workers or 1))
    if workers == 1:
        for idx, case in enumerate(cases, start=1):
            print(f"[START] {idx}/{len(cases)} {case.get('asset_name')}/{case.get('action_name')}", flush=True)
            absorb(_evaluate_case_worker((idx, case, args_dict)))
    else:
        print(f"[INFO] evaluating {len(cases)} cases with workers={workers}", flush=True)
        with concurrent.futures.ProcessPoolExecutor(max_workers=workers) as ex:
            futures = [
                ex.submit(_evaluate_case_worker, (idx, case, args_dict))
                for idx, case in enumerate(cases, start=1)
            ]
            for fut in concurrent.futures.as_completed(futures):
                absorb(fut.result())

    summary = summarize(per_case_rows, errors)
    per_case_rows.sort(key=lambda r: (str(r.get("class")), str(r.get("asset_name")), str(r.get("action_name")), str(r.get("variant"))))
    per_phase_rows.sort(key=lambda r: (str(r.get("class")), str(r.get("asset_name")), str(r.get("action_name")), str(r.get("variant")), int(r.get("phase_index", 0))))
    per_link_rows.sort(key=lambda r: (str(r.get("class")), str(r.get("asset_name")), str(r.get("action_name")), str(r.get("variant")), int(r.get("phase_index", 0)), str(r.get("link"))))
    matched_rows.sort(key=lambda r: (str(r.get("asset_name")), str(r.get("action_name")), str(r.get("variant"))))
    _write_json(diagnose_dir / "ablation_metrics_summary.json", summary)
    _write_json(diagnose_dir / "per_case_metrics.json", per_case_rows)
    _write_json(diagnose_dir / "per_phase_metrics.json", per_phase_rows)
    _write_json(diagnose_dir / "per_link_metrics.json", per_link_rows)
    _write_json(diagnose_dir / "matched_frames.json", matched_rows)
    _write_json(diagnose_dir / "errors.json", errors)
    csv_fields = [
        "case_id",
        "class",
        "asset_name",
        "action_name",
        "variant",
        "PN_gIoU",
        "PN_PC",
        "PN_OC",
        "Dynamic_gIoU",
        "Dynamic_PC",
        "Dynamic_OC",
        "Static_gIoU",
        "Static_PC",
        "Static_OC",
        "matched_frame_indices",
        "matched_timestamps",
        "num_phases",
        "num_eval_states",
        "prediction_trajectory",
        "prediction_plan",
        "prediction_glb",
        "prediction_sequence_source",
        "gt_sequence_source",
        "prediction_num_frames",
        "prediction_last_time_s",
        "prediction_plan_duration_s",
        "prediction_sequence_duration_s",
        "prediction_warning",
    ]
    _write_csv(
        out_dir / "ablation_metrics.csv",
        concise_metric_rows(per_case_rows),
        ["case_id", "class", "asset_name", "action_name", "variant", "PN_gIoU", "PN_PC", "PN_OC"],
    )
    _write_csv(
        out_dir / "ablation_metrics_category_mean.csv",
        category_average_rows(per_case_rows),
        ["class", "variant", "num_cases", "PN_gIoU", "PN_PC", "PN_OC"],
    )
    _write_csv(diagnose_dir / "ablation_metrics_diagnose.csv", per_case_rows, csv_fields)
    _write_csv(
        diagnose_dir / "ablation_metrics_variant_summary.csv",
        _variant_summary_rows(summary),
        [
            "variant",
            "num_cases",
            "PN_gIoU",
            "PN_PC",
            "PN_OC",
            "Dynamic_gIoU",
            "Dynamic_PC",
            "Dynamic_OC",
            "Static_gIoU",
            "Static_PC",
            "Static_OC",
        ],
    )
    print(f"[INFO] wrote {out_dir / 'ablation_metrics.csv'}")
    print(f"[INFO] wrote {out_dir / 'ablation_metrics_category_mean.csv'}")
    print(f"[INFO] diagnose={diagnose_dir}")
    print(json.dumps(summary.get("variants"), ensure_ascii=False, indent=2))
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
